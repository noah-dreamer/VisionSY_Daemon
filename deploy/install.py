#!/usr/bin/env python3
"""Interactive production deployment, invoked after install.sh prepares Linux."""

import argparse
import base64
import errno
import fcntl
import getpass
import ipaddress
import json
import os
from pathlib import Path
import platform
import re
import secrets
import socket
import subprocess
import sys
import tempfile
import time


ROOT = Path(__file__).resolve().parent.parent
COMPOSE_DIR = ROOT / "deploy/docker"
ENV_FILE = COMPOSE_DIR / ".env.install"
STATE_DIR = COMPOSE_DIR / ".install"
ADMIN_EMAIL = "admin@example.com"


class InstallError(Exception):
    pass


def atomic_write(path, text, mode=0o600):
    """Never leave half-written keys/configuration after an interrupted installation."""
    path = Path(path)
    if path.is_symlink():
        raise InstallError(f"拒绝覆盖符号链接：{path}")
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            os.fchmod(handle.fileno(), mode)
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def read_config(path):
    """Read only the installer's own literal env format. Never source shell code."""
    if not path.exists():
        return {}
    if path.is_symlink():
        raise InstallError(f"安装配置不能是符号链接：{path}")
    result = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        match = re.fullmatch(r"([A-Z][A-Z0-9_]*)='([^'\r\n]*)'", line)
        if not match or match[1] in result:
            raise InstallError(".env.install 格式错误；请恢复该文件的备份，避免重新生成已有数据库密钥。")
        result[match[1]] = match[2]
    return result


def write_config(path, values):
    lines = ["# Generated by VisionSY install.sh. Contains secrets; do not commit."]
    for key, value in values.items():
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", key) or any(c in str(value) for c in "'\\\r\n\0"):
            raise InstallError(f"配置 {key} 包含不支持的字符。")
        lines.append(f"{key}='{value}'")
    atomic_write(path, "\n".join(lines) + "\n")


def validate_bind_ip(value):
    try:
        return str(ipaddress.IPv4Address(value))
    except ipaddress.AddressValueError:
        raise InstallError("请输入监听 IPv4 地址，如 0.0.0.0、127.0.0.1 或本机内网 IP。") from None


def validate_port(value):
    if not value.isascii() or not value.isdecimal() or not 1 <= int(value) <= 65535:
        raise InstallError("端口应为 1–65535 的整数。")
    return str(int(value))


def media_path(value):
    if any(c in value for c in "'\\\r\n\0$"):
        raise InstallError("媒体目录路径不能包含引号、反斜杠、换行或美元符号；支持空格。")
    path = Path(value).expanduser()
    if not path.is_absolute():
        path = COMPOSE_DIR / path
    path = path.resolve()
    path.mkdir(parents=True, exist_ok=True)
    if not path.is_dir():
        raise InstallError("媒体路径必须是目录。")
    # Verify this mounted NAS permits ordinary writes and renames, without touching user files.
    with tempfile.TemporaryDirectory(prefix=".visionsy-install-", dir=path) as temporary:
        probe = Path(temporary) / "write-check"
        probe.write_bytes(b"VisionSY installation check\n")
        probe.rename(Path(temporary) / "rename-check")
    return str(path)


def prompt(label, default="", validator=None):
    while True:
        suffix = f" [{default}]" if default else ""
        value = input(f"{label}{suffix}：").strip() or default
        try:
            return validator(value) if validator else value
        except (InstallError, OSError) as error:
            print(f"  {error}", file=sys.stderr)


def admin_password():
    while True:
        value = getpass.getpass(f"设置 {ADMIN_EMAIL} 的密码（至少 8 字符，直接回车自动生成）：")
        if not value:
            return secrets.token_urlsafe(24), True
        if len(value) < 8 or len(value.encode("utf-8")) > 72:
            print("密码至少需要 8 个字符，UTF-8 长度不能超过 72 字节。", file=sys.stderr)
            continue
        if getpass.getpass("再次输入管理员密码：") != value:
            print("两次输入不一致，请重试。", file=sys.stderr)
            continue
        return value, False


def default_ip():
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as connection:
            connection.connect(("192.0.2.1", 80))  # route selection only; sends no packet
            return connection.getsockname()[0]
    except OSError:
        return "127.0.0.1"


def application_url(bind_ip, port):
    host = default_ip() if bind_ip == "0.0.0.0" else bind_ip
    return f"http://{host}" + (f":{port}" if port != "80" else "")


def make_config(existing, project, answers):
    config = dict(existing)
    if existing:
        # Lost configuration must never silently rotate the keys of an existing database.
        for key in ("APP_KEY", "DB_PASSWORD", "DB_ROOT_PASSWORD", "INTERNAL_API_SECRET"):
            if not existing.get(key) or existing[key].startswith("<"):
                raise InstallError(f"已有安装缺失 {key}；请恢复原有配置，不能自动替换已有密钥。")
    else:
        config.update({
            "APP_KEY": "base64:" + base64.b64encode(secrets.token_bytes(32)).decode("ascii"),
            "DB_PASSWORD": secrets.token_hex(32),
            "DB_ROOT_PASSWORD": secrets.token_hex(32),
            "INTERNAL_API_SECRET": secrets.token_hex(32),
        })
    # Deployment exposes an HTTP upstream. Public host/protocol belong to the reverse proxy.
    config.pop("INSTALL_MODE", None)
    config.pop("INSTALL_DOMAIN", None)
    config.update({
        "INSTALL_PROJECT": project,
        "INSTALL_BIND_IP": answers["bind_ip"],
        "APP_IMAGE_TAG": f"{project}-installed",
        "APP_NAME": "VisionSY", "APP_ENV": "production", "APP_DEBUG": "false",
        "APP_URL": existing.get("APP_URL", f"http://127.0.0.1:{answers['port']}"),
        "APP_PORT": answers["port"], "SERVER_NAME": ":80",
        "APP_LOCALE": "zh_CN", "APP_FALLBACK_LOCALE": "zh_CN",
        "DB_CONNECTION": "mysql", "DB_HOST": "127.0.0.1", "DB_PORT": "3306",
        "DB_DATABASE": "visionsy", "DB_USERNAME": "visionsy",
        "SESSION_DRIVER": "database", "SESSION_COOKIE": f"{project}_session",
        "CACHE_STORE": "database", "QUEUE_CONNECTION": "database", "DB_QUEUE_RETRY_AFTER": "3700",
        "DB_QUEUE_DEFAULT": "default", "DB_QUEUE_SCAN": "scan",
        "DB_QUEUE_DERIVATIVES": "derivatives", "DB_QUEUE_UPLOAD": "upload",
        "LOG_CHANNEL": "stderr", "LOG_LEVEL": "info",
        # Only explicit Docker subnet(s) are trusted, never arbitrary public proxy headers.
        "TRUSTED_PROXY_IPS": answers["proxies"],
        "DAM_HOST_MANAGED": answers["media"],
        "MEDIA_MANAGED_ROOT": "/data/visionsy/managed",
        "MEDIA_ALLOWED_ROOTS": "/data/visionsy/managed",
        "MEDIA_DIRECT_SERVE": "true", "MEDIA_GUEST_BROWSE": "true",
        "MEDIA_TEACHER_CAN_UPLOAD": "true", "MEDIA_MAX_UPLOAD_MB": "512",
        "MEDIA_WATERMARK_TEXT": "VisionSY",
        "MEDIA_SCAN_EXCLUDE": "._*,Thumbs.db,.DS_Store,@eaDir",
        "MEDIA_SCAN_STALE_LOCK_MINUTES": "75",
        "MAIL_MAILER": existing.get("MAIL_MAILER", "log"),
        "MAIL_FROM_ADDRESS": existing.get("MAIL_FROM_ADDRESS", "no-reply@example.com"),
        "MAIL_FROM_NAME": "VisionSY",
        "PUBLIC_STORAGE_URL": existing.get("PUBLIC_STORAGE_URL", "/storage"),
        "VISION_RESOURCE_BASE_URL": existing.get("VISION_RESOURCE_BASE_URL", "/media"),
        "VISION_SITE_URL": existing.get("VISION_SITE_URL", ""),
        "VISION_PUBLIC_SITE_URL": existing.get("VISION_PUBLIC_SITE_URL", ""),
        "VISION_AUTH_URL": existing.get("VISION_AUTH_URL", ""),
        "VISION_EXTERNAL_TRANSFER_BASE_URL": existing.get("VISION_EXTERNAL_TRANSFER_BASE_URL", ""),
        "VISION_LAN_TRANSFER_BASE_URL": existing.get("VISION_LAN_TRANSFER_BASE_URL", ""),
        "INTRANET_PROBE_URL": existing.get("INTRANET_PROBE_URL", ""),
    })
    return config


class Installer:
    def __init__(self, project):
        self.project = project
        self.docker = (["sudo"] if os.environ.get("VISIONSY_DOCKER_SUDO") == "1" else []) + ["docker"]
        self.config = {}

    def run(self, args, *, capture=False, data=None, retries=1, output=None):
        # The generated env file wins over unrelated DB_*/APP_* variables in the invoking shell.
        environment = os.environ.copy()
        for key in self.config:
            environment.pop(key, None)
        environment.pop("COMPOSE_PROFILES", None)
        environment.pop("COMPOSE_FILE", None)
        for attempt in range(retries):
            result = subprocess.run(args, cwd=COMPOSE_DIR, env=environment, text=True,
                                    input=data, stdout=subprocess.PIPE if capture else output,
                                    stderr=subprocess.PIPE if capture else None, check=False)
            if result.returncode == 0:
                return result.stdout or ""
            if attempt + 1 < retries:
                print(f"[install] 命令失败，{3 * (attempt + 1)} 秒后重试...", flush=True)
                time.sleep(3 * (attempt + 1))
        # Never echo command input (administrator password) or container environment.
        if capture and result.stderr:
            print(result.stderr, file=sys.stderr)
        raise InstallError(f"命令失败（退出码 {result.returncode}）：{' '.join(args)}")

    def compose(self, *args, **kwargs):
        command = self.docker + ["compose", "--project-name", self.project,
                                 "-f", "compose.prod.yaml",
                                 "-f", "compose.install.yaml", "--env-file", ".env.install"]
        return self.run(command + list(args), **kwargs)

    def artisan(self, *args, **kwargs):
        return self.compose("exec", "-T", "app", "php", "artisan", *args, **kwargs)

    def preflight(self, existing):
        endpoint = os.environ.get("DOCKER_HOST") or self.run(
            self.docker + ["context", "inspect", "--format", "{{.Endpoints.docker.Host}}"], capture=True).strip()
        if not endpoint.startswith("unix://"):
            raise InstallError("安装器需要本机 Docker（unix socket），不能对远程 Docker 上下文部署本机目录。")
        version = self.run(self.docker + ["compose", "version", "--short"], capture=True).strip().lstrip("v")
        numbers = re.match(r"(\d+)\.(\d+)\.(\d+)", version)
        if not numbers or tuple(map(int, numbers.groups())) < (2, 35, 0):
            raise InstallError("Docker Compose 需要 2.35 或更新版本（使用配置覆盖和卷子目录挂载）。")
        print(f"[install] 环境就绪：Linux {platform.machine()}、Python {platform.python_version()}、Compose {version}")
        if existing and existing.get("INSTALL_PROJECT") != self.project:
            raise InstallError("此目录已安装到另一个 Docker 项目；请使用原来的 --project 参数。")
        volumes = self.run(self.docker + ["volume", "ls", "--filter",
                            f"label=com.docker.compose.project={self.project}", "--format", "{{.Name}}"], capture=True)
        containers = self.run(self.docker + ["ps", "-aq", "--filter",
                               f"label=com.docker.compose.project={self.project}"], capture=True)
        if not existing and (volumes.strip() or containers.strip()):
            raise InstallError("该项目已有容器或数据卷，但安装配置缺失。请恢复 .env.install，或选择新的 --project 名称。")

    def configure(self, existing):
        print("\n[install] 配置应用监听地址、端口与媒体目录（直接回车采用默认值）。")
        bind_ip = prompt("应用监听 IP（0.0.0.0 允许其他主机访问）",
                         existing.get("INSTALL_BIND_IP", "0.0.0.0"), validate_bind_ip)
        port = prompt("应用 HTTP 端口", existing.get("APP_PORT", "8000"), validate_port)
        media = prompt("宿主机媒体目录（使用 NAS 时请先在宿主机完成挂载）",
                       existing.get("DAM_HOST_MANAGED", str(COMPOSE_DIR / "data/media")), media_path)
        return {"bind_ip": bind_ip, "port": port, "media": media,
                "proxies": existing.get("TRUSTED_PROXY_IPS", "127.0.0.1")}

    def check_ports(self, answers):
        owned = self.run(self.docker + ["ps", "--filter",
                         f"label=com.docker.compose.project={self.project}",
                         "--format", "{{.Ports}}"], capture=True)
        ports = [(answers["port"], answers["bind_ip"])]
        for port, address in ports:
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
                try:
                    probe.bind((address, int(port)))
                except PermissionError:
                    # The rootful Docker daemon can publish privileged ports even when this user cannot bind them.
                    continue
                except OSError as error:
                    if error.errno != errno.EADDRINUSE:
                        raise InstallError(f"无法检查端口 {port}：{error}") from None
                    if not re.search(rf":{re.escape(port)}->", owned):
                        raise InstallError(f"宿主机端口 {port} 已被其他服务占用，请改用其他端口或先处理冲突。") from None

    def set_trusted_subnet(self):
        network = f"{self.project}_visionsy"
        subnets = json.loads(self.run(self.docker + ["network", "inspect", network,
                                  "--format", "{{json .IPAM.Config}}"], capture=True))
        networks = [entry["Subnet"] for entry in subnets if entry.get("Subnet")]
        if not networks:
            raise InstallError("无法确定 Docker 网络范围，不能完成应用代理配置。")
        trusted = self.config.get("TRUSTED_PROXY_IPS", "127.0.0.1").split(",")
        self.config["TRUSTED_PROXY_IPS"] = ",".join(dict.fromkeys(trusted + networks))
        write_config(ENV_FILE, self.config)

    def database_container(self):
        # Inspect running containers by labels, independent of the new Compose service list.
        for service in ("db", "app"):
            container = self.run(self.docker + ["ps", "-q", "--filter",
                f"label=com.docker.compose.project={self.project}", "--filter",
                f"label=com.docker.compose.service={service}"], capture=True).strip()
            if container:
                return container.splitlines()[0]
        raise InstallError("未找到运行中的数据库容器；请先启动原部署以完成备份。")

    def stop_previous(self):
        # Stop producers/consumers before stopping MariaDB, independent of docker ps order.
        for service in ("worker", "scheduler", "app", "intranet-probe", "db"):
            containers = self.run(self.docker + ["ps", "-q", "--filter",
                f"label=com.docker.compose.project={self.project}", "--filter",
                f"label=com.docker.compose.service={service}"], capture=True).split()
            for container in containers:
                self.run(self.docker + ["stop", container])

    def backup(self):
        directory = STATE_DIR / "backups"
        directory.mkdir(mode=0o700, exist_ok=True)
        target = directory / (time.strftime("%Y%m%d-%H%M%S") + f"-{secrets.token_hex(3)}.sql")
        print(f"[install] 重复部署前备份数据库：{target}", flush=True)
        # Stream the dump into a private file, rather than keeping the whole database in memory.
        try:
            with target.open("x", encoding="utf-8") as handle:
                os.chmod(target, 0o600)
                self.run(self.docker + ["exec", "-i", self.database_container(), "sh", "-c",
                             'MYSQL_PWD="$MARIADB_ROOT_PASSWORD" mariadb-dump --user=root '
                             '--single-transaction --routines --triggers "$MARIADB_DATABASE"'], output=handle)
        except InstallError:
            target.unlink()
            raise InstallError("数据库备份失败，已停止部署。") from None

    def install(self):
        existing = read_config(ENV_FILE)
        self.config = dict(existing)
        self.preflight(existing)
        print("\n[install] 构建生产镜像（宿主机不需要 PHP、Composer 或 Node.js）...", flush=True)
        self.run(self.docker + ["build", "--build-arg", "INSTALL_COMPOSER_DEV=0", "--tag",
                               f"visionsy-app:{self.project}-installed", str(ROOT / "web")], retries=3)
        # Generate keys before configuration; subsequent runs reuse all existing keys.
        key_config = existing or {
            "APP_KEY": "base64:" + base64.b64encode(secrets.token_bytes(32)).decode("ascii"),
            "DB_PASSWORD": secrets.token_hex(32), "DB_ROOT_PASSWORD": secrets.token_hex(32),
            "INTERNAL_API_SECRET": secrets.token_hex(32),
        }
        print("[install] 已保留原有密钥。" if existing else "[install] 已自动生成独立的数据库密码、应用密钥和内部 API 密钥。")
        answers = self.configure(existing)
        self.check_ports(answers)
        self.config = make_config(key_config, self.project, answers)
        if existing:
            atomic_write(STATE_DIR / (time.strftime("config-%Y%m%d-%H%M%S-") + secrets.token_hex(3) + ".env"),
                         ENV_FILE.read_text(encoding="utf-8"))
        write_config(ENV_FILE, self.config)
        self.compose("config", "--quiet")
        if existing:
            self.backup()
            self.stop_previous()
        print("\n[install] 启动单容器（MariaDB → 数据库迁移 → 网站、队列和调度器）...", flush=True)
        self.compose("up", "-d", "--no-build", "--remove-orphans", "--wait", "--wait-timeout", "300")
        self.set_trusted_subnet()
        # Apply the discovered proxy subnet without changing the running database process.
        self.compose("up", "-d", "--no-build", "--wait", "--wait-timeout", "300")
        print("[install] 初始化默认用户组和媒体目录...", flush=True)
        self.artisan("db:seed", "--class=ProductionSeeder", "--force")
        self.artisan("media:init-managed-source")
        print("\n[install] 最后设置网站管理员；重复安装时已有账号及密码保持不变。")
        if (STATE_DIR / "completed").exists():
            password, generated = secrets.token_urlsafe(24), True
        else:
            password, generated = admin_password()
        output = self.artisan("visionsy:ensure-admin", ADMIN_EMAIL, "--if-missing",
                              "--password-stdin", "--json", capture=True, data=password + "\n")
        result = json.loads(output)
        access_url = application_url(self.config["INSTALL_BIND_IP"], self.config["APP_PORT"])
        if result["changed"]:
            atomic_write(STATE_DIR / "credentials.txt",
                         f"VisionSY 安装时的初始凭据（网站修改密码后，以新密码为准）\n"
                         f"应用直连地址：{access_url}\n账号：{ADMIN_EMAIL}\n密码：{password}\n")
        else:
            print("[install] 已有管理员账号，保留其当前密码。")
        self.artisan("optimize")
        self.compose("exec", "-T", "app", "supervisorctl", "-c", "/etc/visionsy/supervisord.conf",
                     "restart", "application:worker", "application:scheduler")
        self.compose("exec", "-T", "app", "php", "artisan", "visionsy:health-diagnostics")
        health_host = "127.0.0.1" if self.config["INSTALL_BIND_IP"] == "0.0.0.0" else self.config["INSTALL_BIND_IP"]
        self.run(["curl", "--fail", "--silent", "--show-error", "--max-time", "10",
                  "--noproxy", "*", f"http://{health_host}:{self.config['APP_PORT']}/up"], capture=True, retries=3)
        atomic_write(STATE_DIR / "completed", "Installation completed successfully.\n")
        print("\nVisionSY 部署完成")
        print(f"  应用地址：{access_url}")
        print(f"  登录地址：{access_url}/login")
        print(f"  管理后台：{access_url}/admin")
        print(f"  监听地址：{self.config['INSTALL_BIND_IP']}:{self.config['APP_PORT']}（HTTP）")
        print(f"  管理账号：{ADMIN_EMAIL}")
        if result["changed"] and generated:
            print(f"  随机密码：{password}")
        else:
            print("  管理密码：使用你设置的密码" if result["changed"] else "  管理密码：保留原来的密码")
        print(f"  媒体目录：{self.config['DAM_HOST_MANAGED']}（每个图库的 preview/ 保存预览）")
        print(f"  配置文件：{ENV_FILE}")
        print(f"  Docker 项目：{self.project}；单容器部署，数据库仅监听容器内 127.0.0.1")
        if (STATE_DIR / "credentials.txt").exists():
            mode = (STATE_DIR / "credentials.txt").stat().st_mode & 0o777
            print(f"  初始凭据：{STATE_DIR / 'credentials.txt'}（文件权限 {mode:o}）")
        print("  反向代理上游：使用上述 HTTP 应用地址；域名及证书由你的反向代理程序配置。")
        if self.config.get("MAIL_MAILER") == "log":
            print("  邮件当前写入日志；开放用户注册前，请在配置文件中设置真实 SMTP 后重新部署。")


def main():
    parser = argparse.ArgumentParser(description="VisionSY Linux 一键生产安装")
    parser.add_argument("--project", default="visionsy-production", help="独立 Docker 项目名，默认 visionsy-production")
    args = parser.parse_args()
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,39}", args.project):
        parser.error("项目名应为 1–40 个小写字母、数字或短横线，并以字母或数字开头。")
    if args.project == "visionsy":
        parser.error("visionsy 保留给现有开发部署，请使用独立的生产项目名。")
    STATE_DIR.mkdir(mode=0o700, exist_ok=True)
    if STATE_DIR.is_symlink():
        parser.error("安装状态目录不能是符号链接。")
    os.chmod(STATE_DIR, 0o700)
    with (STATE_DIR / "install.lock").open("a", encoding="utf-8") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            parser.error("另一个安装进程正在运行，请等待它结束。")
        try:
            Installer(args.project).install()
        except (InstallError, OSError, ValueError, EOFError) as error:
            print(f"\n[install] 部署未完成：{error}", file=sys.stderr)
            print("已保留配置与数据；修复后可用相同命令重新运行，不会重新生成已有密钥。", file=sys.stderr)
            return 1
        except KeyboardInterrupt:
            print("\n[install] 安装已中断，已生成的配置和数据会保留。", file=sys.stderr)
            return 130
    return 0


if __name__ == "__main__":
    sys.exit(main())
